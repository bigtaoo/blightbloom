#!/usr/bin/env node
// Gate: a DECISION doc may not cite a source file that does not exist.
//
// The third of the doc-consistency gates (design/18 Layer 0, after `determinismLint.test.ts`
// and `engine/stepOrder.test.ts`). It closes the last mechanically-checkable class from the
// 2026-09-03 doc audit (`design/roadmap/16`): the docs here quote real file paths in backticks
// constantly, so a wrong one reads as verified.
//
// ## Why only the DECISION docs
//
// Running the sweep over everything produced 36 hits, 35 of them correct — because
// `design/ROADMAP.md`, `design/roadmap/*` and `README.md` are an APPEND-ONLY HISTORICAL LOG.
// An entry written in August naming `FloorProgress.ts` is not stale; the file really was there,
// and this repo's convention is to supersede a log entry rather than rewrite it. Gating history
// against today's file list would mean either editing the past or carrying an allowlist that
// grows with every deletion forever — and the one real defect the audit found was in a decision
// doc (`design/10` promising a `confirmEdge.test.ts` gate deleted a month earlier).
//
// So: `design/**/*.md` (minus ROADMAP and the log volumes) plus `CLAUDE.md`. Those are the docs
// that describe the CURRENT system and get read as instructions.
//
// ## The rule, and its one deliberate looseness
//
// A token resolves if its BASENAME is a tracked file. Not its full path — the docs cite
// shorthand on purpose (`game/Scene.ts` for `client/src/game/scene/Scene.ts`, `content/drops.ts`
// for `engine/content/drops.ts`), and tightening this to full-path matching would flag ~200
// correct references. Basename matching is what found the real defects; path shorthand is a
// house style, not drift.
//
// Resolution is against `git ls-files` — TRACKED files only, deliberately:
//   * it is the same answer on every machine and in CI, where a filesystem walk is not
//     (`client/dist/version.json` exists after a build and not before, and gitignored build
//     output is exactly what several allowlist entries below are about);
//   * consequence: `git add` a new file BEFORE citing it in a decision doc, or this gate fails.
//     That is the intended order anyway.
//
// Usage (cwd = repo root):
//   node build/checkDocPaths.mjs

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync } from 'node:fs';
import { join, relative } from 'node:path';

/** Extensions worth checking — code, data and assets the docs cite by name. */
const EXT = ['ts', 'tsx', 'mjs', 'js', 'json', 'md', 'png', 'webp', 'ogg', 'mp3', 'wav', 'py', 'html'];
const TOKEN_RE = new RegExp('`([A-Za-z0-9_./@-]+\\.(?:' + EXT.join('|') + '))`', 'g');

