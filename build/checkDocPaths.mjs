/** Every `.md` that describes the CURRENT system: `design/` minus ROADMAP and the log, + CLAUDE.md. */
export function decisionDocs(root) {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const abs = join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name === 'roadmap') continue; // the append-only log — see this file's header
        walk(abs);
      } else if (e.name.endsWith('.md') && e.name !== 'ROADMAP.md') {
        out.push(toPosix(relative(root, abs)));
      }
    }
  };
  walk(join(root, 'design'));
  out.push('CLAUDE.md');
  return out.sort();
}

export function toPosix(p) {
  return p.split('\\').join('/');
}

/** Every backticked path-shaped token in `text`, with the 1-based line it appeared on. */
export function extractPathTokens(text) {
  const out = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    for (const m of lines[i].matchAll(TOKEN_RE)) out.push({ token: m[1], line: i + 1 });
  }
  return out;
}

/**
 * The check itself, over injected inputs so the tests can drive it with synthetic docs.
 *
 * `docs`: Map<relPath, text>. `trackedFiles`: array of repo-relative paths.
 * Returns `{ violations, deadEntries, checked }`.
 */
export function checkDocPaths(docs, trackedFiles, allowlist = ALLOWLIST) {
  const basenames = new Set(trackedFiles.map((f) => toPosix(f).split('/').pop()));
  const allowed = new Map(allowlist.map((e) => [e.token, e.why]));
  const usedAllowEntries = new Set();
  const resolvedAllowEntries = [];

  const violations = [];
  let checked = 0;

  for (const [rel, text] of docs) {
    for (const { token, line } of extractPathTokens(text)) {
      checked++;
      const base = toPosix(token).split('/').pop();
      const resolves = basenames.has(base);
      if (allowed.has(token)) {
        usedAllowEntries.add(token);
        // A token that now resolves does not need an exemption any more.
        if (resolves) resolvedAllowEntries.push(token);
        continue;
      }
      if (!resolves) {
        violations.push(
          `${rel}:${line}  \`${token}\` — no tracked file is named "${base}".\n` +
          `     -> fix the reference, or (if it is a sibling-project path, a third-party internal,\n` +
          `        generated output, or a deliberate record of something deleted) add it to\n` +
          `        build/checkDocPaths.mjs's ALLOWLIST with the reason.`,
        );
      }
    }
  }

  const deadEntries = [];
  for (const [token] of allowed) {
    if (!usedAllowEntries.has(token)) {
      deadEntries.push(`\`${token}\` is allowlisted but no decision doc cites it any more — delete the entry.`);
    }
  }
  for (const token of [...new Set(resolvedAllowEntries)]) {
    deadEntries.push(`\`${token}\` is allowlisted but now RESOLVES — delete the entry, the exemption is stale.`);
  }
  return { violations, deadEntries, checked };
}

/* ── CLI ─────────────────────────────────────────────────────────────────────────────────── */

function main() {
  const root = process.cwd();
  const tracked = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' })
    .split('\n').filter(Boolean);
  const docs = new Map(decisionDocs(root).map((rel) => [rel, readFileSync(join(root, rel), 'utf8')]));
  const { violations, deadEntries, checked } = checkDocPaths(docs, tracked);

  console.log(
    `checkDocPaths: ${checked} path references in ${docs.size} decision docs ` +
    `(${ALLOWLIST.length} allowlisted; ROADMAP + roadmap/ + README are history, out of scope).`,
  );
  if (deadEntries.length) {
    console.log('\nFAILED — the ALLOWLIST has stale entries:\n');
    for (const d of deadEntries) console.log(`  - ${d}`);
  }
  if (violations.length) {
    console.log('\nFAILED — a decision doc cites a file that does not exist:\n');
    for (const v of violations) console.log(v + '\n');
  }
  if (violations.length || deadEntries.length) process.exit(1);
  console.log('OK — every path a decision doc cites resolves, and no exemption is dead.');
}

// Only when run directly, so the test can import the module without tripping the CLI.
if (process.argv[1] && toPosix(process.argv[1]).endsWith('build/checkDocPaths.mjs')) main();
